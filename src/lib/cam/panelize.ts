import JSZip from "jszip";
import type { ApertureShape, Layer, LayerKind, Primitive } from "@/lib/gerber/types";

export const PANEL_DEFAULT = { cols: 7, rows: 6, pitch: 40.508, board: 40, rail: 8, fiducial: 1.0 };

export interface PanelBoard {
  label: string;
  layers: Layer[];
}

export interface PanelSlot {
  col: number;
  row: number;
  board: PanelBoard | null;
}

export interface PanelConfig {
  cols: number;
  rows: number;
  pitch: number;
  board: number;
  rail: number;
  name: string;
  coupons: boolean;
  fiducials: boolean;
}

type Placed = { p: Primitive; dx: number; dy: number };

const k = (v: number) => Math.round(v * 1e6);
const coord = (x: number, y: number) => `X${k(x)}Y${k(y)}`;

function apKey(shape: ApertureShape, w: number, h: number) {
  return `${shape}|${w.toFixed(4)}|${h.toFixed(4)}`;
}

function apDef(code: number, shape: ApertureShape, w: number, h: number) {
  const r = (v: number) => v.toFixed(4).replace(/0+$/, "").replace(/\.$/, "");
  switch (shape) {
    case "R":
      return `%ADD${code}R,${r(w)}X${r(h)}*%`;
    case "O":
      return `%ADD${code}O,${r(w)}X${r(h)}*%`;
    case "P":
      return `%ADD${code}P,${r(w)}X6*%`;
    default:
      return `%ADD${code}C,${r(w)}*%`;
  }
}

/** Re-emit a set of translated primitives as a single RS-274X file (MM, absolute, 3.6). */
function emitGerber(items: Placed[], title: string): string {
  const apertures = new Map<string, { code: number; shape: ApertureShape; w: number; h: number }>();
  let next = 10;
  const use = (shape: ApertureShape, w: number, h: number) => {
    const key = apKey(shape, w, h);
    let a = apertures.get(key);
    if (!a) {
      a = { code: next++, shape, w, h };
      apertures.set(key, a);
    }
    return a.code;
  };

  const body: string[] = [];
  let polarity: boolean | null = null;
  let current = -1;

  for (const { p, dx, dy } of items) {
    const clear = !!p.clear;
    if (polarity !== clear) {
      body.push(clear ? "%LPC*%" : "%LPD*%");
      polarity = clear;
    }
    if (p.t === "line") {
      const code = use("C", Math.max(p.w, 0.01), Math.max(p.w, 0.01));
      if (code !== current) { body.push(`D${code}*`); current = code; }
      body.push("G01*");
      body.push(`${coord(p.x1 + dx, p.y1 + dy)}D02*`);
      body.push(`${coord(p.x2 + dx, p.y2 + dy)}D01*`);
    } else if (p.t === "flash") {
      const code = use(p.shape, Math.max(p.w, 0.01), Math.max(p.h || p.w, 0.01));
      if (code !== current) { body.push(`D${code}*`); current = code; }
      body.push(`${coord(p.x + dx, p.y + dy)}D03*`);
    } else {
      if (p.pts.length < 3) continue;
      body.push("G36*");
      const [first, ...rest] = p.pts;
      body.push(`${coord(first![0] + dx, first![1] + dy)}D02*`);
      for (const pt of rest) body.push(`${coord(pt[0] + dx, pt[1] + dy)}D01*`);
      body.push(`${coord(first![0] + dx, first![1] + dy)}D01*`);
      body.push("G37*");
    }
  }

  const head = [
    `G04 ${title} generated by PCB Checker CAM*`,
    "%FSLAX36Y36*%",
    "%MOMM*%",
    "%LPD*%",
    ...[...apertures.values()].map((a) => apDef(a.code, a.shape, a.w, a.h)),
  ];
  return [...head, ...body, "M02*", ""].join("\n");
}

/** Unified Excellon drill file for the whole panel. */
function emitExcellon(holes: { x: number; y: number; d: number }[], title: string): string {
  const tools = new Map<string, { t: number; d: number }>();
  let t = 1;
  for (const h of holes) {
    const key = h.d.toFixed(3);
    if (!tools.has(key)) tools.set(key, { t: t++, d: Number(key) });
  }
  const lines = [
    "M48",
    `; ${title} - unified panel drill`,
    "METRIC,TZ",
    ...[...tools.values()].map((v) => `T${String(v.t).padStart(2, "0")}C${v.d.toFixed(3)}`),
    "%",
    "G90",
    "G05",
  ];
  for (const [key, v] of tools) {
    lines.push(`T${String(v.t).padStart(2, "0")}`);
    for (const h of holes.filter((x) => x.d.toFixed(3) === key)) {
      lines.push(`X${h.x.toFixed(3)}Y${h.y.toFixed(3)}`);
    }
  }
  lines.push("T00", "M30", "");
  return lines.join("\n");
}

const FILE_NAME: Partial<Record<LayerKind, string>> = {
  top_copper: "PANEL-F_Cu.gtl",
  bottom_copper: "PANEL-B_Cu.gbl",
  top_mask: "PANEL-F_Mask.gts",
  bottom_mask: "PANEL-B_Mask.gbs",
  top_silk: "PANEL-F_Silkscreen.gto",
  bottom_silk: "PANEL-B_Silkscreen.gbo",
  top_paste: "PANEL-F_Paste.gtp",
  bottom_paste: "PANEL-B_Paste.gbp",
  outline: "PANEL-Edge_Cuts.gko",
};

const PANEL_KINDS: LayerKind[] = [
  "top_copper",
  "bottom_copper",
  "top_mask",
  "bottom_mask",
  "top_silk",
  "bottom_silk",
  "top_paste",
  "bottom_paste",
  "outline",
];

function rect(x: number, y: number, w: number, h: number, width: number): Primitive[] {
  return [
    { t: "line", x1: x, y1: y, x2: x + w, y2: y, w: width },
    { t: "line", x1: x + w, y1: y, x2: x + w, y2: y + h, w: width },
    { t: "line", x1: x + w, y1: y + h, x2: x, y2: y + h, w: width },
    { t: "line", x1: x, y1: y + h, x2: x, y2: y, w: width },
  ];
}

export interface PanelResult {
  blob: Blob;
  files: { name: string; bytes: number }[];
  width: number;
  height: number;
  boards: number;
  holes: number;
  warnings: string[];
}

export function panelSize(cfg: PanelConfig) {
  return {
    width: cfg.pitch * cfg.cols - (cfg.pitch - cfg.board) + cfg.rail * 2,
    height: cfg.pitch * cfg.rows - (cfg.pitch - cfg.board) + cfg.rail * 2,
  };
}

export function slotOrigin(cfg: PanelConfig, col: number, row: number) {
  return { x: cfg.rail + col * cfg.pitch, y: cfg.rail + row * cfg.pitch };
}

export async function buildPanel(slots: PanelSlot[], cfg: PanelConfig): Promise<PanelResult> {
  const warnings: string[] = [];
  const { width, height } = panelSize(cfg);
  const filled = slots.filter((s) => s.board);
  if (!filled.length) throw new Error("Panoul nu conține nicio plăcuță.");

  const byKind = new Map<LayerKind, Placed[]>();
  const holes: { x: number; y: number; d: number }[] = [];
  const push = (kind: LayerKind, p: Primitive, dx: number, dy: number) => {
    const arr = byKind.get(kind) ?? [];
    arr.push({ p, dx, dy });
    byKind.set(kind, arr);
  };

  for (const slot of filled) {
    const { x: ox, y: oy } = slotOrigin(cfg, slot.col, slot.row);
    const layers = slot.board!.layers;
    const kinds = new Set(layers.map((l) => l.kind));
    for (const need of ["top_copper", "outline"] as LayerKind[]) {
      if (!kinds.has(need)) warnings.push(`${slot.board!.label}: lipsește stratul ${need}.`);
    }
    for (const layer of layers) {
      if (layer.kind === "drill") {
        for (const h of layer.holes) holes.push({ x: h.x + ox, y: h.y + oy, d: h.d });
      } else if (PANEL_KINDS.includes(layer.kind)) {
        for (const p of layer.primitives) push(layer.kind, p, ox, oy);
      }
    }
  }

  // Panel frame on the outline layer.
  for (const p of rect(0, 0, width, height, 0.2)) push("outline", p, 0, 0);

  // Global fiducials: copper flash + mask and paste openings (3 corners, asymmetric).
  if (cfg.fiducials) {
    const fid: [number, number][] = [
      [cfg.rail / 2, cfg.rail / 2],
      [width - cfg.rail / 2, cfg.rail / 2],
      [cfg.rail / 2, height - cfg.rail / 2],
    ];
    for (const [fx, fy] of fid) {
      push("top_copper", { t: "flash", x: fx, y: fy, shape: "C", w: PANEL_DEFAULT.fiducial, h: PANEL_DEFAULT.fiducial }, 0, 0);
      push("bottom_copper", { t: "flash", x: fx, y: fy, shape: "C", w: PANEL_DEFAULT.fiducial, h: PANEL_DEFAULT.fiducial }, 0, 0);
      push("top_mask", { t: "flash", x: fx, y: fy, shape: "C", w: PANEL_DEFAULT.fiducial * 2, h: PANEL_DEFAULT.fiducial * 2 }, 0, 0);
      push("bottom_mask", { t: "flash", x: fx, y: fy, shape: "C", w: PANEL_DEFAULT.fiducial * 2, h: PANEL_DEFAULT.fiducial * 2 }, 0, 0);
    }
  }

  if (cfg.coupons) for (const [k2, p] of couponPrims(cfg)) push(k2, p, 0, 0);
  holes.push(...toolingHoles(width, height, cfg.rail));

  const zip = new JSZip();
  const files: { name: string; bytes: number }[] = [];
  const add = (name: string, text: string) => {
    zip.file(name, text);
    files.push({ name, bytes: text.length });
  };

  for (const kind of PANEL_KINDS) {
    const items = byKind.get(kind);
    if (!items?.length) continue;
    add(FILE_NAME[kind]!, emitGerber(items, `${cfg.name} ${kind}`));
  }
  if (holes.length) add("PANEL-Unified.drl", emitExcellon(holes, cfg.name));

  const map = [
    `Panou CAM: ${cfg.name}`,
    `Matrice: ${cfg.cols} x ${cfg.rows} (pas ${cfg.pitch} mm), placuta ${cfg.board} x ${cfg.board} mm`,
    `Dimensiune panou: ${width.toFixed(3)} x ${height.toFixed(3)} mm (rame ${cfg.rail} mm)`,
    `Plăcuțe plasate: ${filled.length} / ${cfg.cols * cfg.rows}`,
    "",
    "Pozitie;Coloana;Rand;X (mm);Y (mm);Proiect",
    ...filled.map((s) => {
      const o = slotOrigin(cfg, s.col, s.row);
      return `${s.row * cfg.cols + s.col + 1};${s.col + 1};${s.row + 1};${o.x.toFixed(3)};${o.y.toFixed(3)};${s.board!.label}`;
    }),
    "",
    ...(warnings.length ? ["Avertismente:", ...warnings] : []),
  ].join("\n");
  add("PANEL-harta.txt", map);
  add("date_in_LAYERS.txt", dateInFile("LAYERS", positionTable(slots, cfg.cols, (c, r) => slotOrigin(cfg, c, r)), cfg.name));

  const blob = await zip.generateAsync({ type: "blob" });
  return { blob, files, width, height, boards: filled.length, holes: holes.length, warnings };
}

